const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const frontendPackagePath = path.join(projectRoot, 'frontend', 'package.json');
const frontendOutputPath = path.join(projectRoot, 'frontend', 'src', 'generated', 'buildInfo.ts');
const backendOutputPath = path.join(projectRoot, 'backend', 'generated_build_info.py');

const packageJson = JSON.parse(fs.readFileSync(frontendPackagePath, 'utf8'));
const now = new Date();
const pad = (value) => String(value).padStart(2, '0');
const buildId = [
    now.getFullYear(),
    pad(now.getMonth() + 1),
    pad(now.getDate()),
    `${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`,
].join('.');
const builtAt = now.toISOString();

fs.mkdirSync(path.dirname(frontendOutputPath), { recursive: true });
fs.writeFileSync(
    frontendOutputPath,
    `// Generated by scripts/generate-build-info.js. Do not edit manually.\n` +
    `export const BUILD_INFO = ${JSON.stringify({ version: packageJson.version, buildId, builtAt }, null, 2)} as const;\n`,
    'utf8',
);

fs.writeFileSync(
    backendOutputPath,
    `# Generated by scripts/generate-build-info.js. Do not edit manually.\n` +
    `APP_VERSION = ${JSON.stringify(packageJson.version)}\n` +
    `BUILD_ID = ${JSON.stringify(buildId)}\n` +
    `BUILT_AT = ${JSON.stringify(builtAt)}\n`,
    'utf8',
);

console.log(`Generated build metadata: version ${packageJson.version}, build ${buildId}`);
